import type { KeypadStyle } from './configurations';

export type FinishCategory =
  | 'gloss'
  | 'satin-core'
  | 'satin-classic'
  | 'satin-new'
  | 'arch-matte'
  | 'metal';

export type SurfaceType =
  | 'gloss'
  | 'satin'
  | 'matte'
  | 'metal-brushed'
  | 'metal-polished'
  | 'metal-antique'
  | 'metal-anodized';

export interface LutronFinish {
  /** Unique identifier combining category & code (since WH/BL/TP exist in multiple finish families) */
  id: string;
  /** Official Lutron 2- or 3-letter finish code */
  code: string;
  name: string;
  category: FinishCategory;
  /** Compatible keypad wallplate style */
  style: KeypadStyle;
  surface: SurfaceType;
  /** Calibrated wallplate base hex color */
  hex: string;
  /** Optional slightly shifted swatch accent for metallic UI preview */
  swatchGradient?: string;
  /** PBR properties for the wallplate */
  roughness: number;
  metalness: number;
  clearcoat: number;
  clearcoatRoughness: number;
  /**
   * True if engraving ink/etching should render light-on-dark (white/silver text),
   * false if dark charcoal text on light buttons.
   */
  isDarkButton: boolean;
  /**
   * For Metal wallplates, Lutron ships Midnight (MN) or Black (BL) polymer keypad buttons/insert.
   * When defined, the keypad bezel & buttons use this finish instead of metal.
   */
  pairedButton?: {
    code: string;
    name: string;
    hex: string;
    surface: 'satin' | 'matte';
    roughness: number;
    isDarkButton: boolean;
  };
}

export interface FinishCategoryMeta {
  id: FinishCategory;
  label: string;
  shortLabel: string;
  style: KeypadStyle;
  subtitle: string;
}

